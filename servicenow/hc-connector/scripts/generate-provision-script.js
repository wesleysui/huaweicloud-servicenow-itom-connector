#!/usr/bin/env node
/**
 * Reads every servicenow/hc-connector/tables/*.schema.json and generates a
 * SINGLE idempotent GlideRecord provisioning script covering all of them
 * (in dependency order - accounts/regions before anything that references
 * them), written to
 * servicenow/hc-connector/docs/generated/provision-hc-connector-tables.js.
 *
 * *** UNVERIFIED AGAINST A REAL PDI. *** The only technique proven working
 * in this repo is a single sys_choice row insert (see
 * servicenow/discovery/README.md). Creating whole tables/columns via
 * sys_db_object/sys_dictionary GlideRecord inserts is the same category of
 * operation but has not been tested end-to-end here. Treat this script as
 * a time-saving attempt layered on top of the always-correct manual doc
 * (docs/generated/tables/*.md from generate-table-docs.js), not a
 * guaranteed path. Like the sys_choice insert this session already proved
 * needs Global scope, this almost certainly needs Global scope too - the
 * generated script says so at the top and refuses to explain around it.
 *
 * This script creates tables, columns, and per-field choice values only.
 * It deliberately does NOT attempt to create a composite unique DB
 * constraint for tables declaring `unique_together` (ServiceNow's table
 * editor has no simple UI for that on a custom table, and fabricating an
 * unverified raw DB index is worse than just saying so) - the generated
 * output ends with a printed reminder listing which tables need
 * application-layer upsert-before-insert enforcement instead. See
 * tables/README.md's "Composite uniqueness" section and lib/compositeKey.js.
 *
 * Usage: node servicenow/hc-connector/scripts/generate-provision-script.js
 */

var fs = require('fs');
var path = require('path');

var TABLES_DIR = path.join(__dirname, '..', 'tables');
var OUT_FILE = path.join(__dirname, '..', 'docs', 'generated', 'provision-hc-connector-tables.js');

function loadSchemasInDependencyOrder() {
  var schemas = fs.readdirSync(TABLES_DIR)
    .filter(function (f) { return f.endsWith('.schema.json'); })
    .map(function (f) { return JSON.parse(fs.readFileSync(path.join(TABLES_DIR, f), 'utf8')); });

  // Simple dependency sort: a table with a reference field to another
  // HC ITOM Connector table must be provisioned after the table it references.
  var byName = {};
  schemas.forEach(function (s) { byName[s.scope + '_' + s.name] = s; });

  var ordered = [];
  var visited = {};

  function visit(schema) {
    var fullName = schema.scope + '_' + schema.name;
    if (visited[fullName]) return;
    visited[fullName] = true;
    (schema.fields || []).forEach(function (f) {
      if (f.column_type === 'reference' && byName[f.reference_table]) {
        visit(byName[f.reference_table]);
      }
    });
    ordered.push(schema);
  }

  schemas.forEach(visit);
  return ordered;
}

function jsStringLiteral(s) {
  return JSON.stringify(s);
}

function renderFieldProvisionCall(schema, field) {
  var fullTableName = schema.scope + '_' + schema.name;
  var props = [];
  props.push('element: ' + jsStringLiteral(field.name));
  props.push('column_label: ' + jsStringLiteral(field.label));
  props.push('internal_type: ' + jsStringLiteral(field.column_type === 'reference' ? 'reference' : field.column_type));
  if (field.max_length) props.push('max_length: ' + field.max_length);
  if (field.reference_table) props.push('reference: ' + jsStringLiteral(field.reference_table));
  props.push('mandatory: ' + (!!field.mandatory));
  props.push('unique: ' + (!!field.unique));
  // sys_dictionary.default_value is a string column regardless of the field's own type (ServiceNow
  // convention) - stringify booleans/numbers explicitly rather than leaving this out, which is the
  // exact gap that left active/sync_enabled/state/status defaults missing from generated tables.
  if (field.default_value !== undefined) {
    props.push('default_value: ' + jsStringLiteral(String(field.default_value)));
  }

  var lines = [];
  lines.push('createFieldIfMissing(' + jsStringLiteral(fullTableName) + ', {');
  props.forEach(function (prop, index) {
    lines.push('        ' + prop + (index < props.length - 1 ? ',' : ''));
  });
  lines.push('    });');
  if (field.column_type === 'choice' && field.choices) {
    field.choices.forEach(function (choice) {
      lines.push('    createChoiceIfMissing(' + jsStringLiteral(fullTableName) + ', ' + jsStringLiteral(field.name) + ', ' +
        jsStringLiteral(choice.value) + ', ' + jsStringLiteral(choice.label) + ');');
    });
  }
  return lines.join('\n');
}

function renderScript(schemas) {
  var out = [];
  out.push('// AUTO-GENERATED by scripts/generate-provision-script.js - do not hand-edit, regenerate instead.');
  out.push('// *** UNVERIFIED AGAINST A REAL PDI. *** See the header comment in that script for why.');
  out.push('//');
  out.push('// Run in Background Scripts with Application Scope switched to GLOBAL (same category');
  out.push('// of cross-scope restriction already proven for sys_choice writes in this project - see');
  out.push('// servicenow/discovery/README.md). Creates each HC ITOM Connector table (sys_db_object)');
  out.push('// and its columns (sys_dictionary) if missing. Idempotent: safe to re-run.');
  out.push('(function provisionHcConnectorTables() {');
  out.push('    function createTableIfMissing(tableName, label, scope) {');
  out.push('        var existing = new GlideRecord(\'sys_db_object\');');
  out.push('        existing.addQuery(\'name\', tableName);');
  out.push('        existing.query();');
  out.push('        if (existing.next()) {');
  out.push('            gs.info(\'[HcConnectorProvision] table already exists: \' + tableName);');
  out.push('            return;');
  out.push('        }');
  out.push('        var scopeRec = new GlideRecord(\'sys_scope\');');
  out.push('        scopeRec.addQuery(\'scope\', scope);');
  out.push('        scopeRec.query();');
  out.push('        if (!scopeRec.next()) {');
  out.push('            throw new Error(\'sys_scope not found for scope: \' + scope);');
  out.push('        }');
  out.push('        var t = new GlideRecord(\'sys_db_object\');');
  out.push('        t.initialize();');
  out.push('        t.name = tableName;');
  out.push('        t.label = label;');
  out.push('        t.sys_scope = scopeRec.getUniqueValue();');
  out.push('        t.insert();');
  out.push('        gs.info(\'[HcConnectorProvision] created table: \' + tableName);');
  out.push('    }');
  out.push('');
  out.push('    function createFieldIfMissing(tableName, field) {');
  out.push('        var existing = new GlideRecord(\'sys_dictionary\');');
  out.push('        existing.addQuery(\'name\', tableName);');
  out.push('        existing.addQuery(\'element\', field.element);');
  out.push('        existing.query();');
  out.push('        if (existing.next()) {');
  out.push('            gs.info(\'[HcConnectorProvision] field already exists: \' + tableName + \'.\' + field.element);');
  out.push('            return;');
  out.push('        }');
  out.push('        var d = new GlideRecord(\'sys_dictionary\');');
  out.push('        d.initialize();');
  out.push('        d.name = tableName;');
  out.push('        d.element = field.element;');
  out.push('        d.column_label = field.column_label;');
  out.push('        d.internal_type = field.internal_type;');
  out.push('        if (field.max_length) d.max_length = field.max_length;');
  out.push('        if (field.reference) d.reference = field.reference;');
  out.push('        d.mandatory = !!field.mandatory;');
  out.push('        d.unique = !!field.unique;');
  out.push('        if (field.default_value !== undefined) d.default_value = field.default_value;');
  out.push('        d.insert();');
  out.push('        gs.info(\'[HcConnectorProvision] created field: \' + tableName + \'.\' + field.element);');
  out.push('    }');
  out.push('');
  out.push('    function createChoiceIfMissing(tableName, element, value, label) {');
  out.push('        var existing = new GlideRecord(\'sys_choice\');');
  out.push('        existing.addQuery(\'name\', tableName);');
  out.push('        existing.addQuery(\'element\', element);');
  out.push('        existing.addQuery(\'value\', value);');
  out.push('        existing.query();');
  out.push('        if (existing.next()) return;');
  out.push('        var c = new GlideRecord(\'sys_choice\');');
  out.push('        c.initialize();');
  out.push('        c.name = tableName;');
  out.push('        c.element = element;');
  out.push('        c.value = value;');
  out.push('        c.label = label;');
  out.push('        c.inactive = false;');
  out.push('        c.language = \'\';');
  out.push('        c.insert();');
  out.push('        gs.info(\'[HcConnectorProvision] created choice: \' + tableName + \'.\' + element + \' = \' + value);');
  out.push('    }');
  out.push('');

  schemas.forEach(function (schema) {
    var fullTableName = schema.scope + '_' + schema.name;
    out.push('    // --- ' + schema.label + ' (' + fullTableName + ') ---');
    out.push('    createTableIfMissing(' + jsStringLiteral(fullTableName) + ', ' + jsStringLiteral(schema.label) + ', ' + jsStringLiteral(schema.scope) + ');');
    schema.fields.forEach(function (field) {
      out.push('    ' + renderFieldProvisionCall(schema, field));
    });
    out.push('');
  });

  var uniqueTogetherReminders = [];
  schemas.forEach(function (schema) {
    var fullTableName = schema.scope + '_' + schema.name;
    (schema.unique_together || []).forEach(function (group) {
      uniqueTogetherReminders.push(fullTableName + ': (' + group.join(', ') + ')');
    });
  });
  if (uniqueTogetherReminders.length) {
    out.push('    gs.info(\'[HcConnectorProvision] REMINDER: this script does NOT create composite unique constraints. ' +
      'The following tables need application-layer upsert-before-insert (see lib/compositeKey.js and ' +
      'tables/README.md): ' + uniqueTogetherReminders.join(' | ') + '\');');
  }
  out.push('    gs.info(\'[HcConnectorProvision] done.\');');
  out.push('})();');
  out.push('');

  return out.join('\n');
}

function main() {
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  var schemas = loadSchemasInDependencyOrder();
  fs.writeFileSync(OUT_FILE, renderScript(schemas));
  console.log('wrote ' + path.relative(process.cwd(), OUT_FILE) + ' (' + schemas.length + ' tables, unverified against a real PDI)');
}

module.exports = {
  loadSchemasInDependencyOrder: loadSchemasInDependencyOrder,
  renderFieldProvisionCall: renderFieldProvisionCall,
  renderScript: renderScript
};

if (require.main === module) {
  main();
}
